"""Small, deterministic scanner for common software supply-chain risks."""
import json
import re
from pathlib import PurePosixPath

SEVERITY_WEIGHT = {"critical": 40, "high": 25, "medium": 12, "low": 5, "info": 0}

RULES = {
    "SG-SECRET-001": ("Hard-coded credential", "critical", "secrets", "Remove the credential, rotate it, and load it from a secret manager."),
    "SG-DEPS-001": ("Unpinned Python dependency", "medium", "dependency", "Pin the dependency to an approved version and use a lock file."),
    "SG-DEPS-002": ("Wildcard JavaScript dependency", "medium", "dependency", "Replace wildcard ranges with reviewed, reproducible versions."),
    "SG-DEPS-003": ("Unpinned JavaScript dependency", "low", "dependency", "Use a reviewed version range and commit the package lock file."),
    "SG-LOCK-001": ("Dependency manifest without lock file", "medium", "reproducibility", "Commit a lock file generated by your package manager."),
    "SG-DOCKER-001": ("Container runs as root", "medium", "container", "Create a non-root user and add a USER instruction."),
    "SG-DOCKER-002": ("Unpinned container image", "low", "container", "Pin the base image to a version or digest."),
    "SG-MANIFEST-001": ("Invalid package manifest", "low", "integrity", "Correct the manifest syntax and validate it in CI."),
}

_SECRET_PATTERNS = [
    re.compile(r"(?i)(?:api[_-]?key|secret|password|token)\s*[:=]\s*['\"]?([A-Za-z0-9_\-./+=]{12,})"),
    re.compile(r"\bAKIA[0-9A-Z]{16}\b"),
    re.compile(r"-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----"),
]


def _normalized_path(raw: str) -> str:
    path = PurePosixPath(raw.replace("\\", "/"))
    if path.is_absolute() or ".." in path.parts:
        raise ValueError(f"Unsafe file path: {raw}")
    return str(path)


def _finding(rule_id: str, path: str, message: str, line: int | None = None) -> dict:
    title, severity, category, recommendation = RULES[rule_id]
    return {"rule_id": rule_id, "title": title, "severity": severity, "category": category,
            "file_path": path, "line": line, "message": message, "recommendation": recommendation}


def scan_files(files: list[dict]) -> dict:
    """Scan caller-supplied file contents; never reads arbitrary server paths."""
    normalized: dict[str, str] = {}
    findings: list[dict] = []
    for item in files:
        path = _normalized_path(item["path"])
        content = item["content"]
        normalized[path] = content
        for number, line in enumerate(content.splitlines(), start=1):
            if any(pattern.search(line) for pattern in _SECRET_PATTERNS):
                findings.append(_finding("SG-SECRET-001", path, "A credential-like value appears in source.", number))

    for path, content in normalized.items():
        basename = PurePosixPath(path).name.lower()
        if basename == "requirements.txt":
            for number, line in enumerate(content.splitlines(), 1):
                dep = line.strip()
                if dep and not dep.startswith(("#", "-")) and not re.search(r"===|==|~=|<=|>=|<|>", dep):
                    findings.append(_finding("SG-DEPS-001", path, f"Dependency '{dep}' has no explicit version pin.", number))
        elif basename == "package.json":
            try:
                manifest = json.loads(content)
                for section in ("dependencies", "devDependencies", "optionalDependencies"):
                    for name, version in manifest.get(section, {}).items():
                        version = str(version)
                        if version == "*" or version.lower() == "latest":
                            findings.append(_finding("SG-DEPS-002", path, f"Dependency '{name}' uses '{version}'."))
                        elif version.startswith(("^", "~")):
                            findings.append(_finding("SG-DEPS-003", path, f"Dependency '{name}' allows a floating version range ({version})."))
            except (json.JSONDecodeError, AttributeError):
                findings.append(_finding("SG-MANIFEST-001", path, "package.json is not valid JSON."))
        elif basename == "dockerfile":
            if not re.search(r"(?im)^\s*USER\s+\S+", content):
                findings.append(_finding("SG-DOCKER-001", path, "No USER instruction was found; the image may run as root."))
            for number, line in enumerate(content.splitlines(), 1):
                match = re.match(r"\s*FROM\s+(\S+)", line, re.I)
                if match and ":" not in match.group(1).rsplit("/", 1)[-1] and "@sha256:" not in match.group(1):
                    findings.append(_finding("SG-DOCKER-002", path, f"Base image '{match.group(1)}' has no version tag.", number))

    names = {PurePosixPath(path).name.lower() for path in normalized}
    has_manifest = bool(names & {"requirements.txt", "pyproject.toml", "package.json", "go.mod", "cargo.toml"})
    has_lock = bool(names & {"poetry.lock", "pipfile.lock", "package-lock.json", "pnpm-lock.yaml", "yarn.lock", "cargo.lock", "go.sum"})
    if has_manifest and not has_lock:
        findings.append(_finding("SG-LOCK-001", "", "A dependency manifest was found without a recognized lock file."))

    # One secret finding per file and line, to keep reports readable.
    unique = {(f["rule_id"], f["file_path"], f["line"], f["message"]): f for f in findings}
    findings = list(unique.values())
    score = min(100, sum(SEVERITY_WEIGHT[f["severity"]] for f in findings))
    return {"findings": findings, "risk_score": score, "files_scanned": len(normalized),
            "status": "passed" if not any(f["severity"] in ("critical", "high") for f in findings) else "attention"}
